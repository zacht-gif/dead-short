/**
 * shots.mjs — render the store imagery out of the real game.
 *
 *   node shots.mjs            every shot, into store/screenshots/
 *   node shots.mjs menu       only shots whose id contains "menu"
 *
 * Drives an unmodified index.html in headless Chrome over the DevTools protocol
 * and writes PNGs at exact pixel sizes. index.html is never copied or patched:
 * the script reaches in through window.__wiredDev, so a screenshot cannot drift
 * from what a player actually sees.
 *
 * What makes this different from photographing a hand-played board: every
 * in-game position here comes from __wiredDev.ui.stageSolution(), which replays
 * a solution the solver PROVED and stops partway. So the marketing images carry
 * the same guarantee the game does — nothing staged, nothing faked, no position
 * that a player could not have reached by the rules. They also survive a UI
 * change, because nothing here knows a pixel coordinate.
 *
 * Node 24 ships a global WebSocket, so this needs no dependencies.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { CDP, launch, sleep } from "./chrome.mjs";

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const GAME = pathToFileURL(path.join(ROOT, "index.html")).href;
const OUT = path.join(ROOT, "store", "screenshots");

/* ------------------------------- ingredients ------------------------------ */

// The intro is a one-shot splash on first load. Every shot starts past it.
// A fitted shot never goes below this, so a failed measurement cannot produce
// a sliver of an image.
const MIN_FIT = 320;

const SKIP_INTRO = `document.getElementById('introScreen').classList.add('hidden');`;

// A 6x6, three-pair board with two components, a gate and a patrol. Fixed so
// the editor shot is reproducible; regenerate with __wiredDev.encodeLevel if
// the codec version ever changes, and re-check it still solves.
const DEMO_BOARD =
  "VzF-Nn42fmEuLi4uQS4uLi4uLmMuLi4uQy4uIyMuLi4uLi4uLmIuLi4uQn5HMiwxOjEwOjQ6MH5QMjoxLDQ6NCw0";

/**
 * Stage a level partway through its proven solution.
 *
 * `at` is a fraction of the schedule, not a tick count: pars differ per level,
 * and a fixed count that reads well on Logic Array is most of the way through
 * Breadboard. Fractions keep a shot meaning "about two thirds in" no matter
 * which board it lands on.
 */
const play = (slug, at) => SKIP_INTRO + `
  const d = window.__wiredDev;
  const lv = d.LEVELS.find(l => l.slug === ${JSON.stringify(slug)});
  if (!lv) throw new Error("no level " + ${JSON.stringify(slug)});
  const sol = d.solveLevel(lv);
  d.ui.enterLevel(lv);
  const r = d.ui.stageSolution(lv, sol, Math.round(sol.actions.length * ${at}));
  d.ui.updateHud();
  // The real tick, not 0 — the sparks are wherever the staged run left them,
  // and drawing at tick 0 would put every hazard back at the start of its loop.
  d.ui.draw(r.ticks, 0);
`;

