/* --------------------------------- capture -------------------------------- */

// Dead Short pulses and flashes on infinite CSS loops. Left running, a capture
// samples them at whatever phase the clock happened to be in and no two runs
// match — so pin the looping ones and hold them at t=0.
const PIN_ANIMATIONS = `(async () => {
  for (const a of document.getAnimations()) {
    // pause() BEFORE assigning currentTime. Setting the time on a running
    // animation and pausing afterwards leaves the hold time wherever the clock
    // reached, which is a frame of drift.
    if (a.effect?.getTiming?.().iterations === Infinity) {
      a.pause();
      a.currentTime = 0;
    }
  }
  // Pausing is not the same as the compositor having drawn the paused frame.
  // Two rAFs so the held phase is what actually rasterises.
  await new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)));
})()`;

async function main() {
  const filter = process.argv[2];
  const shots = filter ? SHOTS.filter((s) => s.id.includes(filter)) : SHOTS;
  if (!shots.length) {
    console.error(`No shot id matches "${filter}". Known: ${SHOTS.map((s) => s.id).join(", ")}`);
    process.exit(1);
  }

  await mkdir(OUT, { recursive: true });
  const { cdp, sessionId, dispose } = await launch();
  const problems = [];

  try {
    for (const shot of shots) {
      const dpr = shot.scale ?? 1;
      await cdp.send("Emulation.setDeviceMetricsOverride",
        { width: shot.width, height: shot.height, deviceScaleFactor: dpr, mobile: false }, sessionId);
      await cdp.send("Emulation.setTouchEmulationEnabled",
        { enabled: !!shot.touch, maxTouchPoints: shot.touch ? 5 : 1 }, sessionId);

      // Reload each time so no shot inherits the last one's state.
      const loaded = cdp.once("Page.loadEventFired");
      await cdp.send("Page.navigate", { url: shot.url ?? GAME }, sessionId);
      await loaded;
      await sleep(250);

      const res = await cdp.send("Runtime.evaluate", {
        expression: `(async () => { ${shot.setup} })()`,
        awaitPromise: true, returnByValue: true,
      }, sessionId);
      if (res.exceptionDetails) {
        const d = res.exceptionDetails;
        problems.push(`${shot.id}: ${d.text} ${d.exception?.description ?? ""}`);
        continue;
      }

      await sleep(shot.wait ?? 300);

      // Grow the viewport to whatever the page actually needs. Two passes:
      // making the window taller can reflow content shorter (a scrollbar goes
      // away), and settling once is the difference between a crop and a fit.
      if (shot.fit) {
        let height = shot.height;
        for (let pass = 0; pass < 2; pass++) {
          // Measure the furthest-down visible element, NOT scrollHeight: body
          // carries a min-height, so scrollHeight can never report less than
          // the viewport and a shot can only ever grow. The editor page is
          // shorter than 900 and was padding the bottom third with dead space.
          const { result } = await cdp.send("Runtime.evaluate", {
            expression: `(() => {
              // Skip elements at least as tall as the window: those are layout
              // shells carrying a 100vh min-height, and measuring them just
              // hands back the viewport again — which is what made scrollHeight
              // useless here. Their children are still measured.
              const vh = window.innerHeight;
              let bottom = 0;
              for (const el of document.body.querySelectorAll('*')) {
                const r = el.getBoundingClientRect();
                if (r.width > 0 && r.height > 0 && r.height < vh) {
                  bottom = Math.max(bottom, r.bottom);
                }
              }
              const pad = parseFloat(getComputedStyle(document.body).paddingBottom) || 0;
              return Math.ceil(bottom + pad);
            })()`,
            returnByValue: true,
          }, sessionId);
          const want = Math.max(MIN_FIT, result.value);
          if (want === height && pass > 0) break;
          height = want;
          await cdp.send("Emulation.setDeviceMetricsOverride",
            { width: shot.width, height, deviceScaleFactor: dpr, mobile: false }, sessionId);
          await sleep(120);
        }
        shot.measured = height;
      }

      await cdp.send("Runtime.evaluate",
        { expression: PIN_ANIMATIONS, awaitPromise: true }, sessionId);
      await sleep(80);

      // A shot is only worth what the page actually painted. The cover shipped
      // three quarters blank and every existing check passed it, because blank
      // is perfectly deterministic — so reproducibility proved nothing here.
      // Measure instead: the root element has to cover the viewport it is shot
      // in, or the difference is page background that nobody drew.
      const { result: cov } = await cdp.send("Runtime.evaluate", {
        expression: `(() => {
          const r = document.documentElement.getBoundingClientRect();
          return { w: Math.round(r.width), h: Math.round(r.height),
                   vw: window.innerWidth, vh: window.innerHeight };
        })()`,
        returnByValue: true,
      }, sessionId);
      const { w: pw, h: ph, vw, vh } = cov.value;
      if (pw < vw - 1 || ph < vh - 1) {
        problems.push(`${shot.id}: the page paints only ${pw}x${ph} of a ${vw}x${vh} ` +
          `viewport — the rest of the capture would be blank`);
        continue;
      }

      const { data } = await cdp.send("Page.captureScreenshot",
        { format: "png", captureBeyondViewport: false }, sessionId);
      const buf = Buffer.from(data, "base64");
      await writeFile(path.join(OUT, shot.file), buf);
      const h = shot.measured ?? shot.height;
      console.log(`${shot.file.padEnd(24)} ${shot.width * dpr}x${h * dpr}` +
        `${dpr !== 1 ? ` (${dpr}x)` : ""}${shot.measured ? " (fitted)" : ""}` +
        `  ${(buf.length / 1024).toFixed(0)} KB`);
    }
  } finally {
    await dispose();
  }

  if (problems.length) {
    console.error("\nShots that failed to set up:");
    for (const p of problems) console.error("  " + p);
    process.exitCode = 1;
  } else {
    console.log(`\nWrote to ${path.relative(ROOT, OUT)}/`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
